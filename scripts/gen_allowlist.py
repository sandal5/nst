#!/usr/bin/env python3
"""Generate gateway/src/allowlist.js from the registry domain list.

Reads data/domains.txt in the jp-procurement working dir (fallbacks:
nst-repo/data/domains.csv) and writes a JS module exporting ALLOWED_HOSTS.
Run after the registry domain list changes, then redeploy the gateway.
"""
import csv
import os
import sys

CANDIDATES_TXT = [
    os.path.expanduser("~/workspace/jp-procurement/data/domains.txt"),
    os.path.expanduser("~/workspace/nst-repo/data/domains.txt"),
]
OUT = os.path.expanduser("~/workspace/nst-repo/gateway/src/allowlist.js")


def load_domains():
    for p in CANDIDATES_TXT:
        if os.path.exists(p):
            with open(p, encoding="utf-8") as f:
                return sorted({l.strip() for l in f if l.strip()})
    csv_path = os.path.expanduser("~/workspace/nst-repo/data/domains.csv")
    with open(csv_path, encoding="utf-8-sig") as f:
        return sorted({r["domain"] for r in csv.DictReader(f) if r.get("domain")})


def main():
    domains = load_domains()
    lines = [",\n".join(f'  "{d}"' for d in domains)]
    js = (
        "// Generated by scripts/gen_allowlist.py from the project registry\n"
        f"// domain list ({len(domains)} hosts). Do not edit by hand.\n"
        "export const ALLOWED_HOSTS = new Set([\n" + lines[0] + "\n]);\n"
    )
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(js)
    print(f"wrote {OUT} with {len(domains)} hosts")


if __name__ == "__main__":
    sys.exit(main())
