#!/usr/bin/env python3
"""Generate gateway/src/allowlist.js from the project registry itself.

The allowlist is EVERY host that appears in the registry's own fields:
  - master_source_list.csv: official_domain column
  - master_source_list.csv: host of source_url_kkj
  - master_source_list.csv: host of daily_collection_target (when it is a URL)
  - verify_all.csv: hosts of the checked URL and its redirect final URL
    (when that file is available)

Earlier versions generated the list from data/domains.txt (homepage domains
only). That missed hosts that appear only as recorded target pages on sibling
subdomains (e.g. an issuer homepage domain vs. its procurement subdomain),
and the gateway refused those fetches with "host not in allowlist"
(2026-10-27 night run: 7 high-profile rows blocked). Deriving the list from
the registry's own recorded URLs removes that class of gap by construction.

Writes gateway/src/allowlist.js in BOTH the jp-procurement working dir and
the nst-repo clone when they exist. After regenerating, the gateway must be
redeployed (git push triggers the Cloudflare build) for changes to apply.
"""
import csv
import os
from urllib.parse import urlparse

JP = os.path.expanduser("~/workspace/jp-procurement")
REPO = os.path.expanduser("~/workspace/nst-repo")


def host_of(url):
    if not url:
        return ""
    url = url.strip()
    if not url.startswith("http"):
        return ""
    try:
        return urlparse(url).netloc.lower()
    except Exception:
        return ""


def collect_hosts():
    hosts = set()
    master = os.path.join(JP, "data/master_source_list.csv")
    with open(master, encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            d = (r.get("official_domain") or "").strip().lower()
            if d:
                hosts.add(d)
            for col in ("source_url_kkj", "daily_collection_target"):
                h = host_of(r.get(col) or "")
                if h:
                    hosts.add(h)
    verify = os.path.join(JP, "data/verify_all.csv")
    if os.path.exists(verify):
        with open(verify, encoding="utf-8-sig") as f:
            for r in csv.DictReader(f):
                for col in ("url", "final_url", "checked_url", "source_url"):
                    h = host_of(r.get(col) or "")
                    if h:
                        hosts.add(h)
    return sorted(hosts)


def main():
    hosts = collect_hosts()
    body = ",\n".join(f'  "{h}"' for h in hosts)
    js = (
        "// Generated by scripts/gen_allowlist.py from the project registry's\n"
        f"// own recorded hosts ({len(hosts)} hosts). Do not edit by hand.\n"
        "export const ALLOWED_HOSTS = new Set([\n" + body + "\n]);\n"
    )
    for out_dir in (os.path.join(JP, "gateway/src"), os.path.join(REPO, "gateway/src")):
        if os.path.isdir(out_dir):
            out = os.path.join(out_dir, "allowlist.js")
            with open(out, "w", encoding="utf-8") as f:
                f.write(js)
            print(f"wrote {out} with {len(hosts)} hosts")
    for probe in ("www.metro.tokyo.lg.jp", "www.pref.kanagawa.jp",
                  "www.city.kyoto.lg.jp", "www.pref.osaka.lg.jp",
                  "www.city.yokohama.lg.jp", "www.p-portal.go.jp",
                  "www.geps.go.jp"):
        print(f"  {probe}: {'OK' if probe in hosts else 'MISSING'}")


if __name__ == "__main__":
    main()
